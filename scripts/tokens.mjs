#!/usr/bin/env node
/**
 * Keeps the three copies of the design tokens in step with
 * `registry/stellify/stellify-base.css`, the source of truth:
 *
 *  - `registry.json` → the `stellify-base` item's `cssVars` and `css`
 *  - `.storybook/shadcn/theme.css` → the Tailwind `@theme inline` wiring
 *
 *   node scripts/tokens.mjs          write both
 *   node scripts/tokens.mjs --check  exit 1 if either is stale
 *
 * The CSS parser is deliberately small: it understands only the shapes used in
 * stellify-base.css (flat rule blocks of `--name: value;` and one `@layer base`).
 */
import { readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const SOURCE = join(root, "registry/stellify/stellify-base.css")
const REGISTRY = join(root, "registry.json")
const THEME = join(root, ".storybook/shadcn/theme.css")

/** Colors exposed as Tailwind utilities (`bg-surface-2`, `text-danger`…). */
export const COLOR_TOKENS = [
  "background", "foreground",
  "surface-1", "surface-2", "surface-3", "surface-overlay",
  "brand", "brand-foreground", "brand-subtle",
  "muted", "muted-foreground", "hairline", "field", "field-hover", "field-edge", "focus",
  "card", "card-foreground", "popover", "popover-foreground",
  "primary", "primary-foreground", "secondary", "secondary-foreground",
  "accent", "accent-foreground", "destructive", "destructive-foreground",
  "border", "input", "ring",
  ...["success", "warning", "danger", "info"].flatMap((s) => [s, `${s}-foreground`, `${s}-subtle`]),
  "chart-1", "chart-2", "chart-3", "chart-4", "chart-5",
  "sidebar", "sidebar-foreground", "sidebar-primary", "sidebar-primary-foreground",
  "sidebar-accent", "sidebar-accent-foreground", "sidebar-border", "sidebar-ring",
]

/** Tailwind radius scale folded onto the two radii of the system. */
export const RADIUS_THEME = {
  "radius-sm": "var(--radius-control)",
  "radius-md": "var(--radius-control)",
  "radius-lg": "var(--radius-container)",
  "radius-xl": "var(--radius-container)",
}

const stripComments = (css) => css.replace(/\/\*[\s\S]*?\*\//g, "")

/** Splits CSS into top-level `{ selector, body }` blocks (brace-balanced). */
function blocks(css) {
  const out = []
  let depth = 0
  let start = 0
  let open = -1
  for (let i = 0; i < css.length; i++) {
    if (css[i] === "{") {
      if (depth === 0) open = i
      depth++
    } else if (css[i] === "}") {
      depth--
      if (depth === 0) {
        out.push({ selector: css.slice(start, open).trim().replace(/\s+/g, " "), body: css.slice(open + 1, i) })
        start = i + 1
      }
    }
  }
  return out
}

function declarations(body) {
  const vars = {}
  for (const decl of body.split(";")) {
    const m = decl.trim().match(/^--([\w-]+)\s*:\s*([\s\S]+)$/)
    if (m) vars[m[1]] = m[2].trim().replace(/\s+/g, " ")
  }
  return vars
}

function properties(body) {
  const props = {}
  for (const decl of body.split(";")) {
    const m = decl.trim().match(/^([\w-]+)\s*:\s*([\s\S]+)$/)
    if (m) props[m[1]] = m[2].trim().replace(/\s+/g, " ")
  }
  return props
}

/** Nested rules (`@layer base { … }`) → shadcn's `css` object shape. */
function nested(body) {
  const out = {}
  for (const b of blocks(body)) {
    const inner = blocks(b.body)
    out[b.selector] = inner.length ? nested(b.body) : properties(b.body)
  }
  return out
}

export function parseBase(cssText = readFileSync(SOURCE, "utf8")) {
  const css = stripComments(cssText)
  const light = {}
  const dark = {}
  const extra = {}
  for (const { selector, body } of blocks(css)) {
    if (selector === ":root") Object.assign(light, declarations(body))
    else if (selector === ".dark") Object.assign(dark, declarations(body))
    else if (selector === ":root, .dark") {
      const shared = declarations(body)
      Object.assign(light, shared)
      Object.assign(dark, shared)
    } else if (selector.startsWith("@layer")) extra[selector] = nested(body)
    else extra[selector] = properties(body)
  }
  return { light, dark, extra }
}

export function expectedItemCss({ extra }) {
  return { '@import "tw-animate-css"': {}, ...extra }
}

export function expectedThemeVars() {
  const theme = {}
  for (const t of COLOR_TOKENS) theme[`color-${t}`] = `var(--${t})`
  return { ...theme, ...RADIUS_THEME }
}

function themeCss() {
  const lines = Object.entries(expectedThemeVars()).map(([k, v]) => `  --${k}: ${v};`)
  return `@import "tailwindcss";
@import "tw-animate-css";

/* Generated by scripts/tokens.mjs from registry/stellify/stellify-base.css.
   Do not edit by hand: run \`node scripts/tokens.mjs\`. */
@import "../../registry/stellify/stellify-base.css";

/* Dark mode driven by a \`.dark\` class on an ancestor (Storybook toolbar
   toggles it on <html>), matching the consumer setup. */
@custom-variant dark (&:where(.dark, .dark *));

/* Same block the registry ships as \`cssVars.theme\`. */
@theme inline {
${lines.join("\n")}
}
`
}

function main() {
  const check = process.argv.includes("--check")
  const parsed = parseBase()
  const registry = JSON.parse(readFileSync(REGISTRY, "utf8"))
  const item = registry.items.find((i) => i.name === "stellify-base")
  item.cssVars = { theme: expectedThemeVars(), light: parsed.light, dark: parsed.dark }
  item.css = expectedItemCss(parsed)
  const nextRegistry = JSON.stringify(registry, null, 2) + "\n"
  const nextTheme = themeCss()

  const stale = []
  if (readFileSync(REGISTRY, "utf8") !== nextRegistry) stale.push("registry.json")
  if (readFileSync(THEME, "utf8") !== nextTheme) stale.push(".storybook/shadcn/theme.css")

  if (check) {
    if (stale.length) {
      console.error(`Stale tokens in: ${stale.join(", ")}. Run node scripts/tokens.mjs`)
      process.exit(1)
    }
    return
  }
  writeFileSync(REGISTRY, nextRegistry)
  writeFileSync(THEME, nextTheme)
  console.log(stale.length ? `updated ${stale.join(", ")}` : "already in sync")
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main()
